_COMPILED = [(ids, re.compile(pat), exp) for ids, pat, exp in TERMS]
_URL = re.compile(r"https?://\S+|<[^>\s]*://[^>]*>")


class Glossary:
    """한 브리핑(슬랙 1건 = 텔레그램 분할본 묶음)에서 공유한다. explain() 은 메시지에 실리는 순서대로 부를 것."""

    def __init__(self):
        self.used = set()

    def explain(self, text):
        if not text:
            return text
        blocked = [m.span() for m in _URL.finditer(text)]
        picks = []  # (start, end, ids, explanation)
        claimed = set()
        for ids, rx, exp in _COMPILED:
            if any(i in self.used or i in claimed for i in ids):
                continue
            for m in rx.finditer(text):
                s, e = m.span()
                if text[e:e + 1] in ("(", "（"):
                    continue  # 이미 괄호 설명이 붙어 있음
                if any(bs < e and s < be for bs, be in blocked):
                    continue
                if any(ps < e and s < pe for ps, pe, _, _ in picks):
                    continue
                picks.append((s, e, ids, exp))
                claimed.update(ids)
                break
        for s, e, ids, exp in sorted(picks, reverse=True):
            text = f"{text[:e]}({exp}){text[e:]}"
        self.used |= claimed
        return text


# 해요체 → 합니다체 (문장 끝에서만). 긴 어미를 먼저.
_POLITE = [
    (r"거예요", "것입니다"), (r"이에요", "입니다"), (r"예요", "입니다"),
    (r"했어요", "했습니다"), (r"였어요", "였습니다"), (r"됐어요", "됐습니다"),
    (r"었어요", "었습니다"), (r"았어요", "았습니다"), (r"겠어요", "겠습니다"),
    (r"있어요", "있습니다"), (r"없어요", "없습니다"), (r"같아요", "같습니다"),
    (r"보여요", "보입니다"), (r"돼요", "됩니다"), (r"해요", "합니다"), (r"줘요", "줍니다"),
    (r"드려요", "드립니다"),
]
_POLITE_RX = [(re.compile(p + r"(?=[\s.!?,)\]'\"_*~]|$)"), r) for p, r in _POLITE]
# 테스트·점검용: 남아 있으면 안 되는 해요체 어미
HAEYO = re.compile(r"(해요|이에요|예요|어요|아요|여요|워요|돼요|드려요|네요|죠)(?=[\s.!?,)\]'\"_*~]|$)")


def polite(text):
    for rx, rep in _POLITE_RX:
        text = rx.sub(rep, text)
    return text
